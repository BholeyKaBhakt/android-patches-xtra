    /** Decrypts just enough to read meta.json (also checks the password). */
    public static JSONObject readMeta(Context ctx, Uri uri, char[] pw) throws IOException {
        InputStream in = ctx.getContentResolver().openInputStream(uri);
        if (in == null) throw new IOException("Cannot open the file");
        try (ZipInputStream zis = new ZipInputStream(ZCrypto.decrypt(new BufferedInputStream(in, 1 << 16), pw))) {
            ZipEntry e = zis.getNextEntry();
            if (e == null || !e.getName().equals("meta.json")) throw new IOException("Not a Zangi backup");
            return new JSONObject(readAll(zis));
        } catch (JSONException ex) {
            throw new IOException("Corrupt backup metadata", ex);
        }
    }

    /** Problem with restoring this backup into the installed app, or null if it's fine. */
    public static String checkCompatible(Context ctx, JSONObject meta) {
        if (!ctx.getPackageName().equals(meta.optString("package")))
            return "This backup is for " + meta.optString("package") + ".";
        if (meta.optInt("format", 0) > FORMAT)
            return "This backup was made by a newer version of the backup feature.";
        if (meta.optLong("versionCode", 0) > versionCode(ctx))
            return "This backup was made by Zangi " + meta.optString("versionName") + " (" + meta.optLong("versionCode")
                    + "), newer than the installed " + versionName(ctx) + " (" + versionCode(ctx) + "). Update Zangi first.";
        return null;
    }

    /**
     * internal/* goes to a staging dir swapped in on the next main-process start (before Zangi opens
     * its DBs); external/* (media) is written straight to the media dir.
     */
    public static JSONObject stageArchive(Context ctx, Uri uri, char[] pw, Progress pr) throws IOException {
        if (!BUSY.compareAndSet(false, true)) throw new IOException("A backup or restore is already running");
        File pend = new File(dataDir(ctx), PENDING_DIR);
        try {
            deleteTree(pend);
            new File(ctx.getNoBackupFilesDir(), INDEX_FILE + PENDING_SUFFIX).delete();
            if (!pend.mkdirs()) throw new IOException("Cannot create the staging folder");
            File ext = ctx.getExternalFilesDir(null);
            InputStream in = ctx.getContentResolver().openInputStream(uri);
            if (in == null) throw new IOException("Cannot open the file");
            JSONObject meta = null;
            boolean hasDb = false, hasAccount = false;
            try (ZipInputStream zis = new ZipInputStream(ZCrypto.decrypt(new BufferedInputStream(in, 1 << 16), pw))) {
                ZipEntry e;
                int n = 0;
                while ((e = zis.getNextEntry()) != null) {
                    String name = e.getName();
                    if (e.isDirectory()) continue;
                    if (name.contains("..") || name.startsWith("/") || name.contains("\\"))
                        throw new IOException("Unsafe entry: " + name);
                    if (name.equals("meta.json")) {
                        meta = new JSONObject(readAll(zis));
                        String problem = checkCompatible(ctx, meta);
                        if (problem != null) throw new IOException(problem);
                        continue;
                    }
                    if (meta == null) throw new IOException("Not a Zangi backup");
                    File target;
                    if (name.startsWith("internal/")) {
                        String rel = name.substring("internal/".length());
                        if (rel.startsWith("databases/") && rel.endsWith(".db")) hasDb = true;
                        if (rel.equals("shared_prefs/" + ACCOUNT_PREFS + ".xml")) hasAccount = true;
                        target = new File(pend, rel);
                    } else if (name.startsWith("external/")) {
                        if (ext == null) continue;
                        target = new File(ext, name.substring("external/".length()));
                    } else {
                        continue;
                    }
                    if (pr != null && (++n % 10) == 0) pr.update("Restoring " + name, n, 0);
                    writeAtomically(zis, target);
                }
            } catch (JSONException ex) {
                throw new IOException("Corrupt backup metadata", ex);
            }
            if (meta == null) throw new IOException("Not a Zangi backup");
            if (!hasDb || !hasAccount) throw new IOException("The backup is incomplete (no account database)");
            if (!new File(pend, READY_MARK).createNewFile()) throw new IOException("Cannot finalize the restore");
            Log.i(TAG, "restore staged, account=" + meta.optString("account"));
            return meta;
        } catch (IOException e) {
            deleteTree(pend);
            throw e;
        } finally {
            BUSY.set(false);
        }
    }

    /** Newest data archive in a backup folder (null if none). */
    public static Uri newestArchive(Context ctx, Uri tree) {
        String[] best = null;
        for (String[] c : listChildren(ctx.getContentResolver(), tree, DocumentsContract.getTreeDocumentId(tree))) {
            if (c[1].startsWith(DATA_PREFIX) && c[1].endsWith(EXT) && (best == null || c[1].compareTo(best[1]) > 0))
                best = c;
        }
        return best == null ? null : DocumentsContract.buildDocumentUriUsingTree(tree, best[0]);
    }

    /** Folder restore: stages the newest data archive, then decrypts media/ back into place. */
    public static JSONObject stageFromFolder(Context ctx, Uri tree, char[] pw, Progress pr) throws IOException {
        Uri newest = newestArchive(ctx, tree);
        if (newest == null) throw new IOException("No " + DATA_PREFIX + "*" + EXT + " in the selected folder");
        JSONObject meta = stageArchive(ctx, newest, pw, pr);
        ContentResolver cr = ctx.getContentResolver();
        File ext = ctx.getExternalFilesDir(null);
        String mediaId = null;
        for (String[] c : listChildren(cr, tree, DocumentsContract.getTreeDocumentId(tree)))
            if (c[1].equals(MEDIA_DIR) && DocumentsContract.Document.MIME_TYPE_DIR.equals(c[2])) mediaId = c[0];
        int[] count = {0, 0};
        Map<String, String> index = new HashMap<>();
        if (mediaId != null && ext != null) restoreMedia(cr, tree, mediaId, ext, ext, pw, pr, count, index);
        // The folder already holds these files: seed the mirror index so the next backup doesn't
        // re-encrypt them all (applied together with the restore).
        writeIndex(new File(ctx.getNoBackupFilesDir(), INDEX_FILE + PENDING_SUFFIX), tree.toString(), index);
        try { meta.put("media_restored", count[0]); meta.put("media_failed", count[1]); } catch (JSONException ignored) {}
        return meta;
    }

    static void restoreMedia(ContentResolver cr, Uri tree, String dirId, File dest, File extRoot, char[] pw,
                             Progress pr, int[] count, Map<String, String> index) {
        for (String[] c : listChildren(cr, tree, dirId)) {
            if (DocumentsContract.Document.MIME_TYPE_DIR.equals(c[2])) {
                restoreMedia(cr, tree, c[0], new File(dest, c[1]), extRoot, pw, pr, count, index);
                continue;
            }
            if (!c[1].endsWith(EXT)) continue;
            File d = new File(dest, c[1].substring(0, c[1].length() - EXT.length()));
            if (pr != null) pr.update("Media " + d.getName(), count[0], 0);
            try (InputStream in = cr.openInputStream(DocumentsContract.buildDocumentUriUsingTree(tree, c[0]))) {
                if (in == null) continue;
                writeAtomically(ZCrypto.decrypt(new BufferedInputStream(in, 1 << 16), pw), d);
                index.put(extRoot.toURI().relativize(d.toURI()).getPath(), d.length() + ":" + d.lastModified());
                count[0]++;
            } catch (Exception e) {
                count[1]++;
                Log.w(TAG, "media restore skip " + c[1] + ": " + e);
            }
        }
    }

    public static boolean hasPendingRestore(Context ctx) {
        return new File(new File(dataDir(ctx), PENDING_DIR), READY_MARK).exists();
    }

    /** Ends every process of this app and relaunches it through the :zbrestart trampoline. */
    public static void restartApp(Activity a) {
        Intent i = new Intent(a, ZRestartActivity.class);
        i.putExtra(ZRestartActivity.EXTRA_PID, Process.myPid());
        i.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK | Intent.FLAG_ACTIVITY_CLEAR_TASK);
        a.startActivity(i);
        a.finishAffinity();
        killOtherAppProcesses(a);
        Runtime.getRuntime().exit(0);
    }

    static void killOtherAppProcesses(Context ctx) {
        try {
            ActivityManager am = (ActivityManager) ctx.getSystemService(Context.ACTIVITY_SERVICE);
            List<ActivityManager.RunningAppProcessInfo> ps = am.getRunningAppProcesses();
            if (ps == null) return;
            for (ActivityManager.RunningAppProcessInfo p : ps) {
                if (p.uid == Process.myUid() && p.pid != Process.myPid() && !p.processName.endsWith(ZRestartActivity.PROCESS))
                    Process.killProcess(p.pid);
            }
        } catch (Throwable ignored) {}
    }

