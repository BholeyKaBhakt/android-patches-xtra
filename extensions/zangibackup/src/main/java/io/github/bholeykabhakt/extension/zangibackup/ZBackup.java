    /** MainApplication.attachBaseContext(): swap a staged restore in before any DB is opened. */
    static void applyPendingRestore(Context base) {
        try {
            if (base == null || !isMainProcess(base)) return;
            File data = dataDir(base);
            File pend = new File(data, PENDING_DIR);
            if (!pend.exists()) return;
            if (!new File(pend, READY_MARK).exists()) {      // interrupted staging -> discard
                deleteTree(pend);
                return;
            }
            for (String sub : new String[]{"databases", "shared_prefs", "files"}) {
                File staged = new File(pend, sub);
                if (!staged.isDirectory()) continue;
                File live = new File(data, sub);
                File[] kids = live.listFiles();
                if (kids != null) for (File k : kids) {
                    if (sub.equals("shared_prefs") && k.getName().equals(OWN_PREFS + ".xml")) continue;
                    deleteTree(k);
                }
                live.mkdirs();
                File[] in = staged.listFiles();
                if (in != null) for (File k : in) {
                    File dst = new File(live, k.getName());
                    if (!k.renameTo(dst)) { copyTree(k, dst); deleteTree(k); }
                }
            }
            deleteTree(pend);
            File index = new File(base.getNoBackupFilesDir(), INDEX_FILE);
            File seeded = new File(base.getNoBackupFilesDir(), INDEX_FILE + PENDING_SUFFIX);
            if (!seeded.exists() || !seeded.renameTo(index)) index.delete();
            base.getSharedPreferences(OWN_PREFS, 0).edit()
                    .putLong("restored_at", System.currentTimeMillis()).remove("last_sig").commit();
            Log.i(TAG, "pending restore applied");
        } catch (Throwable t) {
            Log.e(TAG, "applyPendingRestore failed", t);
        }
    }

    /** MainActivity.onStop(): background backup to the chosen folder when something changed. */
    static void autoBackup(Activity a) {
        final Context ctx = a.getApplicationContext();
        SharedPreferences p = prefs(ctx);
        if (!p.getBoolean("auto", false) || folder(ctx) == null || !hasPassword(ctx) || !isLoggedIn(ctx)) return;
        long now = System.currentTimeMillis();
        if (now - p.getLong("last_auto_try", 0) < AUTO_MIN_INTERVAL_MS) return;
        if (dataSignature(ctx).equals(p.getString("last_sig", ""))) return;
        p.edit().putLong("last_auto_try", now).apply();
        new Thread(() -> {
            try {
                backupToFolder(ctx, null);
            } catch (Throwable t) {
                Log.e(TAG, "auto backup failed", t);
                prefs(ctx).edit().putString("last_error", String.valueOf(t.getMessage())).apply();
            }
        }, "ZBackup-auto").start();
    }

