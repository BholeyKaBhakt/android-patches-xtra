    static SharedPreferences prefs(Context c) {
        return c.getApplicationContext().getSharedPreferences(OWN_PREFS, 0);
    }

    public static boolean hasPassword(Context c) {
        return prefs(c).getString("password", "").length() > 0;
    }

    static char[] password(Context c) {
        return prefs(c).getString("password", "").toCharArray();
    }

    /** Sets/changes the password; a new mirror salt forces the media mirror to be re-encrypted. */
    public static void setPassword(Context c, String pw) {
        prefs(c).edit().putString("password", pw)
                .putString("mirror_salt", Base64.encodeToString(ZCrypto.newSalt(), Base64.NO_WRAP))
                .apply();
        new File(c.getNoBackupFilesDir(), INDEX_FILE).delete();
        ZCrypto.forgetKeys();
    }

    static byte[] mirrorSalt(Context c) {
        String s = prefs(c).getString("mirror_salt", "");
        if (s.isEmpty()) {
            s = Base64.encodeToString(ZCrypto.newSalt(), Base64.NO_WRAP);
            prefs(c).edit().putString("mirror_salt", s).apply();
        }
        return Base64.decode(s, Base64.NO_WRAP);
    }

    public static Uri folder(Context c) {
        String s = prefs(c).getString("tree", "");
        return s.isEmpty() ? null : Uri.parse(s);
    }

    public static void setFolder(Context c, Uri tree) {
        c.getContentResolver().takePersistableUriPermission(tree,
                Intent.FLAG_GRANT_READ_URI_PERMISSION | Intent.FLAG_GRANT_WRITE_URI_PERMISSION);
        prefs(c).edit().putString("tree", tree.toString()).apply();
        new File(c.getNoBackupFilesDir(), INDEX_FILE).delete();
    }

    /**
     * After a restore is staged: keep using its password, and for a folder restore keep backing up
     * to that folder. Our prefs survive the swap, so without this a reinstall silently stops backups.
     */
    public static void adoptRestoreSource(Context c, Uri tree, char[] pw) {
        SharedPreferences.Editor e = prefs(c).edit();
        if (tree != null || !hasPassword(c)) {
            e.putString("password", new String(pw))
                    .putString("mirror_salt", Base64.encodeToString(ZCrypto.newSalt(), Base64.NO_WRAP));
        }
        if (tree != null) {
            try {
                c.getContentResolver().takePersistableUriPermission(tree,
                        Intent.FLAG_GRANT_READ_URI_PERMISSION | Intent.FLAG_GRANT_WRITE_URI_PERMISSION);
                e.putString("tree", tree.toString()).putBoolean("auto", true);
            } catch (SecurityException ignored) {
            }
        }
        e.commit();
    }

    public static boolean autoEnabled(Context c) {
        return prefs(c).getBoolean("auto", false);
    }

    public static void setAuto(Context c, boolean on) {
        prefs(c).edit().putBoolean("auto", on).apply();
    }

