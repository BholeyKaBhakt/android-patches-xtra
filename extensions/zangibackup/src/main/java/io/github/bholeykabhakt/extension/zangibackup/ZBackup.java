    static void pruneArchives(ContentResolver cr, Uri tree, String root) {
        List<String[]> archives = new ArrayList<>();
        for (String[] c : listChildren(cr, tree, root)) {
            if (c[1].startsWith(DATA_PREFIX) && c[1].endsWith(EXT)) archives.add(c);
            else if (c[1].startsWith(DATA_PREFIX) && c[1].endsWith(".part")) delete(cr, tree, c[0]);
        }
        Collections.sort(archives, (a, b) -> b[1].compareTo(a[1]));
        for (int i = KEEP_DATA_ARCHIVES; i < archives.size(); i++) delete(cr, tree, archives.get(i)[0]);
    }

    static void delete(ContentResolver cr, Uri tree, String docId) {
        try { DocumentsContract.deleteDocument(cr, DocumentsContract.buildDocumentUriUsingTree(tree, docId)); }
        catch (Exception ignored) {}
    }

    /** Resolves/creates nested folders under a tree once per backup pass. */
    static final class DirCache {
        final ContentResolver cr;
        final Uri tree;
        final Map<String, String> ids = new HashMap<>();
        final Map<String, Map<String, String>> listings = new HashMap<>();

        DirCache(ContentResolver cr, Uri tree, String root) {
            this.cr = cr;
            this.tree = tree;
            ids.put("", root);
        }

        String child(String parentId, String name) {
            Map<String, String> l = listings.get(parentId);
            if (l == null) {
                l = new HashMap<>();
                for (String[] c : listChildren(cr, tree, parentId)) l.put(c[1], c[0]);
                listings.put(parentId, l);
            }
            return l.get(name);
        }

        String dir(String path) throws IOException {
            String id = ids.get(path);
            if (id != null) return id;
            int slash = path.lastIndexOf('/');
            String parent = dir(slash < 0 ? "" : path.substring(0, slash));
            String leaf = slash < 0 ? path : path.substring(slash + 1);
            id = child(parent, leaf);
            if (id == null) {
                Uri made = DocumentsContract.createDocument(cr, DocumentsContract.buildDocumentUriUsingTree(tree, parent),
                        DocumentsContract.Document.MIME_TYPE_DIR, leaf);
                if (made == null) throw new IOException("Cannot create folder " + path);
                id = DocumentsContract.getDocumentId(made);
                listings.get(parent).put(leaf, id);
            }
            ids.put(path, id);
            return id;
        }
    }

    /** rows of {docId, displayName, mime, size} */
    static List<String[]> listChildren(ContentResolver cr, Uri tree, String parentId) {
        List<String[]> out = new ArrayList<>();
        Uri kids = DocumentsContract.buildChildDocumentsUriUsingTree(tree, parentId);
        try (Cursor c = cr.query(kids, new String[]{
                DocumentsContract.Document.COLUMN_DOCUMENT_ID,
                DocumentsContract.Document.COLUMN_DISPLAY_NAME,
                DocumentsContract.Document.COLUMN_MIME_TYPE,
                DocumentsContract.Document.COLUMN_SIZE}, null, null, null)) {
            while (c != null && c.moveToNext()) {
                out.add(new String[]{c.getString(0), c.getString(1), c.getString(2),
                        c.isNull(3) ? "0" : String.valueOf(c.getLong(3))});
            }
        } catch (Exception e) {
            Log.w(TAG, "listChildren", e);
        }
        return out;
    }

    static Map<String, String> readIndex(File f, String tree) {
        Map<String, String> m = new HashMap<>();
        try (BufferedReader r = new BufferedReader(new FileReader(f))) {
            if (!tree.equals(r.readLine())) return m;
            String line;
            while ((line = r.readLine()) != null) {
                int t = line.lastIndexOf('\t');
                if (t > 0) m.put(line.substring(0, t), line.substring(t + 1));
            }
        } catch (IOException ignored) {}
        return m;
    }

    static void writeIndex(File f, String tree, Map<String, String> m) {
        File tmp = new File(f.getPath() + ".tmp");
        try (Writer w = new FileWriter(tmp)) {
            w.write(tree + "\n");
            for (Map.Entry<String, String> e : m.entrySet()) w.write(e.getKey() + "\t" + e.getValue() + "\n");
        } catch (IOException e) {
            return;
        }
        tmp.renameTo(f);
    }

    static void addTree(ZipOutputStream zos, File dir, String prefix, boolean deflate, Progress pr) throws IOException {
        if (dir == null || !dir.isDirectory()) return;
        List<File> all = new ArrayList<>();
        listFiles(dir, all);
        int i = 0;
        for (File f : all) {
            i++;
            if (denied(f.getName())) continue;
            String rel = dir.toURI().relativize(f.toURI()).getPath();
            if (pr != null) pr.update(prefix + rel, i, all.size());
            putFile(zos, prefix + rel, f, deflate);
        }
    }

    static void listFiles(File dir, List<File> out) {
        File[] fs = dir.listFiles();
        if (fs == null) return;
        Arrays.sort(fs);
        for (File f : fs) {
            if (f.isDirectory()) listFiles(f, out);
            else if (f.isFile()) out.add(f);
        }
    }

    static void putBytes(ZipOutputStream zos, String name, byte[] b) throws IOException {
        ZipEntry e = new ZipEntry(name);
        zos.putNextEntry(e);
        zos.write(b);
        zos.closeEntry();
    }

    /** STORED for already-compressed media (needs size + CRC up front), DEFLATED otherwise. */
    static void putFile(ZipOutputStream zos, String name, File f, boolean deflate) throws IOException {
        ZipEntry e = new ZipEntry(name);
        e.setTime(f.lastModified());
        if (!deflate) {
            CRC32 crc = new CRC32();
            byte[] buf = new byte[1 << 16];
            try (InputStream in = new FileInputStream(f)) {
                int n;
                while ((n = in.read(buf)) > 0) crc.update(buf, 0, n);
            }
            e.setMethod(ZipEntry.STORED);
            e.setSize(f.length());
            e.setCompressedSize(f.length());
            e.setCrc(crc.getValue());
        }
        zos.putNextEntry(e);
        try (InputStream in = new BufferedInputStream(new FileInputStream(f), 1 << 16)) {
            copyStream(in, zos);
        }
        zos.closeEntry();
    }

    static void writeAtomically(InputStream in, File target) throws IOException {
        File parent = target.getParentFile();
        if (parent != null) parent.mkdirs();
        File tmp = new File(parent, "." + target.getName() + ".zbpart");
        try (OutputStream os = new BufferedOutputStream(new FileOutputStream(tmp), 1 << 16)) {
            copyStream(in, os);
        } catch (IOException e) {
            tmp.delete();
            throw e;
        }
        if (target.exists()) target.delete();
        if (!tmp.renameTo(target)) {
            tmp.delete();
            throw new IOException("Cannot write " + target);
        }
    }

    static String readAll(InputStream in) throws IOException {
        java.io.ByteArrayOutputStream bos = new java.io.ByteArrayOutputStream();
        copyStream(in, bos);
        return bos.toString("UTF-8");
    }

    static void copyStream(InputStream in, OutputStream out) throws IOException {
        byte[] buf = new byte[1 << 16];
        int n;
        while ((n = in.read(buf)) > 0) out.write(buf, 0, n);
    }

    static void copyTree(File src, File dst) throws IOException {
        if (src.isDirectory()) {
            dst.mkdirs();
            File[] kids = src.listFiles();
            if (kids != null) for (File k : kids) copyTree(k, new File(dst, k.getName()));
        } else {
            try (InputStream in = new FileInputStream(src); OutputStream out = new FileOutputStream(dst)) {
                copyStream(in, out);
            }
        }
    }

    static void deleteTree(File f) {
        if (f.isDirectory()) {
            File[] kids = f.listFiles();
            if (kids != null) for (File k : kids) deleteTree(k);
        }
        f.delete();
    }

    static final class CountingOut extends java.io.FilterOutputStream {
        long count;
        CountingOut(OutputStream out) { super(out); }
        @Override public void write(int b) throws IOException { out.write(b); count++; }
        @Override public void write(byte[] b, int off, int len) throws IOException { out.write(b, off, len); count += len; }
    }
