    /** Encrypted data archive into the chosen folder (keeps the last few) + incremental media mirror. */
    public static String backupToFolder(Context ctx, Progress pr) throws IOException {
        Uri tree = folder(ctx);
        if (tree == null) throw new IOException("Choose a backup folder first");
        if (!hasPassword(ctx)) throw new IOException("Set a backup password first");
        if (!BUSY.compareAndSet(false, true)) throw new IOException("A backup or restore is already running");
        try {
            ContentResolver cr = ctx.getContentResolver();
            String sig = dataSignature(ctx);
            String root = DocumentsContract.getTreeDocumentId(tree);
            Uri rootUri = DocumentsContract.buildDocumentUriUsingTree(tree, root);
            String name = DATA_PREFIX + stamp() + EXT;
            Uri part = DocumentsContract.createDocument(cr, rootUri, MIME, name + ".part");
            if (part == null) throw new IOException("Cannot write to the backup folder");
            long size;
            try {
                OutputStream raw = cr.openOutputStream(part, "w");
                if (raw == null) throw new IOException("Cannot write to the backup folder");
                CountingOut counting = new CountingOut(new BufferedOutputStream(raw, 1 << 16));
                OutputStream enc = ZCrypto.encrypt(counting, password(ctx));
                writeArchive(ctx, enc, false, pr);              // closes enc -> counting -> raw
                size = counting.count;
                Uri done = DocumentsContract.renameDocument(cr, part, name);
                if (done == null) throw new IOException("Cannot finalize " + name);
            } catch (IOException | RuntimeException e) {
                try { DocumentsContract.deleteDocument(cr, part); } catch (Exception ignored) {}
                throw e;
            }
            pruneArchives(cr, tree, root);
            int mirrored = mirrorMedia(ctx, tree, root, pr);
            prefs(ctx).edit()
                    .putLong("last_backup", System.currentTimeMillis())
                    .putLong("last_auto_try", System.currentTimeMillis())   // no auto run right after a manual one
                    .putString("last_name", name)
                    .putLong("last_size", size)
                    .putString("last_sig", sig)
                    .remove("last_error")
                    .apply();
            Log.i(TAG, "backup ok: " + name + " (" + size + " B, media +" + mirrored + ")");
            return name;
        } finally {
            BUSY.set(false);
        }
    }

    /** One self-contained encrypted file (optionally with all media) to any picked destination. */
    public static void exportToUri(Context ctx, Uri dest, boolean includeMedia, Progress pr) throws IOException {
        if (!hasPassword(ctx)) throw new IOException("Set a backup password first");
        if (!BUSY.compareAndSet(false, true)) throw new IOException("A backup or restore is already running");
        try {
            OutputStream raw = ctx.getContentResolver().openOutputStream(dest, "wt");
            if (raw == null) throw new IOException("Cannot open the destination");
            writeArchive(ctx, ZCrypto.encrypt(new BufferedOutputStream(raw, 1 << 16), password(ctx)), includeMedia, pr);
            prefs(ctx).edit().putLong("last_export", System.currentTimeMillis()).apply();
        } finally {
            BUSY.set(false);
        }
    }

    static void writeArchive(Context ctx, OutputStream os, boolean includeMedia, Progress pr) throws IOException {
        File data = dataDir(ctx);
        ZipOutputStream zos = new ZipOutputStream(os);
        try {
            putBytes(zos, "meta.json", buildMeta(ctx, includeMedia).toString(2).getBytes("UTF-8"));
            File[] dbs = new File(data, "databases").listFiles();
            if (dbs != null) {
                Arrays.sort(dbs);
                for (File f : dbs) {
                    String n = f.getName();
                    if (!f.isFile() || denied(n) || n.endsWith("-wal") || n.endsWith("-shm")
                            || n.endsWith("-journal")) continue;
                    if (pr != null) pr.update("Database " + n, 0, 0);
                    snapshotDb(ctx, f, zos, "internal/databases/" + n);
                }
            }
            File[] prefs = new File(data, "shared_prefs").listFiles();
            if (prefs != null) for (File f : prefs) {
                if (f.isFile() && f.getName().endsWith(".xml") && !denied(f.getName()))
                    putFile(zos, "internal/shared_prefs/" + f.getName(), f, true);
            }
            addTree(zos, new File(data, "files"), "internal/files/", true, pr);
            if (includeMedia) {
                File ext = ctx.getExternalFilesDir(null);
                if (ext != null) addTree(zos, ext, "external/", false, pr);
            }
        } catch (JSONException e) {
            throw new IOException(e);
        } finally {
            zos.close();
        }
    }

    static JSONObject buildMeta(Context ctx, boolean includeMedia) throws JSONException {
        JSONObject m = new JSONObject();
        m.put("format", FORMAT);
        m.put("package", ctx.getPackageName());
        m.put("versionName", versionName(ctx));
        m.put("versionCode", versionCode(ctx));
        m.put("created", System.currentTimeMillis());
        m.put("account", accountNumber(ctx));
        m.put("device", Build.MANUFACTURER + " " + Build.MODEL);
        m.put("sdk", Build.VERSION.SDK_INT);
        m.put("media", includeMedia);
        return m;
    }

    /** VACUUM INTO gives a transactionally consistent copy while Zangi keeps the DB open (WAL). */
    static void snapshotDb(Context ctx, File db, ZipOutputStream zos, String entry) throws IOException {
        File snap = new File(ctx.getCacheDir(), "zb_snap.db");
        snap.delete();
        boolean ok = false;
        SQLiteDatabase s = null;
        try {
            s = SQLiteDatabase.openDatabase(db.getAbsolutePath(), null, SQLiteDatabase.OPEN_READONLY);
            s.execSQL("VACUUM INTO ?", new Object[]{snap.getAbsolutePath()});
            ok = snap.length() > 0;
        } catch (Throwable t) {
            Log.w(TAG, "VACUUM INTO failed for " + db.getName() + ", raw copy instead", t);
        } finally {
            if (s != null) try { s.close(); } catch (Throwable ignored) {}
        }
        if (ok) {
            putFile(zos, entry, snap, true);
        } else {
            putFile(zos, entry, db, true);
            File wal = new File(db.getPath() + "-wal");
            if (wal.exists()) putFile(zos, entry + "-wal", wal, true);
        }
        snap.delete();
        new File(snap.getPath() + "-journal").delete();
    }

    /** Encrypts new/changed media into folder/media/&lt;rel&gt;.zbk; one shared salt = one key derivation. */
    static int mirrorMedia(Context ctx, Uri tree, String root, Progress pr) throws IOException {
        File ext = ctx.getExternalFilesDir(null);
        if (ext == null || !ext.isDirectory()) return 0;
        ContentResolver cr = ctx.getContentResolver();
        File indexFile = new File(ctx.getNoBackupFilesDir(), INDEX_FILE);
        Map<String, String> index = readIndex(indexFile, tree.toString());
        List<File> all = new ArrayList<>();
        listFiles(ext, all);
        byte[] salt = mirrorSalt(ctx);
        char[] pw = password(ctx);
        DirCache dirs = new DirCache(cr, tree, root);
        int copied = 0, i = 0;
        for (File f : all) {
            i++;
            String rel = ext.toURI().relativize(f.toURI()).getPath();
            if (denied(f.getName()) || f.getName().startsWith(".")) continue;
            String stamp = f.length() + ":" + f.lastModified();
            if (stamp.equals(index.get(rel))) continue;
            if (pr != null) pr.update("Media " + rel, i, all.size());
            int slash = rel.lastIndexOf('/');
            String dir = MEDIA_DIR + (slash >= 0 ? "/" + rel.substring(0, slash) : "");
            String leaf = (slash >= 0 ? rel.substring(slash + 1) : rel) + EXT;
            try {
                String parent = dirs.dir(dir);
                String existing = dirs.child(parent, leaf);
                if (existing != null) DocumentsContract.deleteDocument(cr, DocumentsContract.buildDocumentUriUsingTree(tree, existing));
                Uri doc = DocumentsContract.createDocument(cr, DocumentsContract.buildDocumentUriUsingTree(tree, parent), MIME, leaf);
                if (doc == null) throw new IOException("create failed");
                OutputStream raw = cr.openOutputStream(doc, "w");
                if (raw == null) throw new IOException("open failed");
                try (InputStream in = new FileInputStream(f);
                     OutputStream os = ZCrypto.encrypt(new BufferedOutputStream(raw, 1 << 16), pw, salt)) {
                    copyStream(in, os);
                }
                index.put(rel, stamp);
                copied++;
            } catch (Exception e) {
                Log.w(TAG, "mirror skip " + rel + ": " + e);
            }
        }
        writeIndex(indexFile, tree.toString(), index);
        return copied;
    }

