    static String processName() {
        if (Build.VERSION.SDK_INT >= 28) return android.app.Application.getProcessName();
        try (FileInputStream in = new FileInputStream("/proc/self/cmdline")) {
            byte[] b = new byte[256];
            int n = in.read(b), end = 0;
            while (end < n && b[end] != 0) end++;
            return new String(b, 0, end, "UTF-8");
        } catch (Throwable t) {
            return null;
        }
    }

    static boolean isMainProcess(Context ctx) {
        String name = processName();
        return name == null || name.equals(ctx.getPackageName());
    }

